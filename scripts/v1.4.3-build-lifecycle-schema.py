#!/usr/bin/env python3
"""Build exact cumulative lifecycle metadata from the accepted fixture; no live reads.

The P04 manifest and its immutable migration hashes keep their original meaning.
This separate extension captures all lifecycle tables and affected financial DDL.
"""
import argparse
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ('0066-v1.4.3-subscription-lifecycle-foundation.sql',
         '0067-v1.4.3-lifecycle-engine-binding.sql',
         '0068-v1.4.3-provider-and-review-binding.sql',
         '0069-v1.4.3-d1-compatibility.sql',
         '0070-v1.4.3-refund-notification.sql',
         '0071-v1.4.3-refund-contract-retirement.sql')
MARKERS = ('1.4.3-subscription-lifecycle-foundation', '1.4.3-lifecycle-engine-binding',
           '1.4.3-provider-and-review-binding', '1.4.3-d1-compatibility', '1.4.3-refund-notification',
           '1.4.3-refund-contract-retirement')
ENGINE_TABLES = ('subscription_first_recurring_receipts', 'subscription_payment_review_receipts')
PROVIDER_TABLES = ('subscription_invoice_requests', 'subscription_payment_review_settlements')
REFUND_TABLES = ('subscription_refund_cancellations',)
TABLES = ('subscription_billing_contracts', 'subscription_payment_links',
          'subscription_provider_events', 'subscription_provider_commands',
          'paid_subscription_notification_jobs', 'payment_review_resolutions')
FINANCIAL = ('price_book', 'terms_acceptances', 'subscription_orders',
             'payment_events', 'payment_ledger', 'subscriptions',
             'subscription_access_grants', 'payment_reconciliation_items')
OUTPUT = ROOT / 'src/v1.4.3/lifecycle-schema-manifest.mjs'

def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))

def objects(db, tables):
    return [dict(type=t, name=n, table_name=table, sql=sql)
            for t, n, table, sql in db.execute(
                'SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE tbl_name IN (' +
                ','.join('?' for _ in tables) + ') ORDER BY type,name', tables)]

def build():
    db = sqlite3.connect(':memory:')
    ddl = json.loads((ROOT / 'tests/fixtures/base-schema.json').read_text(
        encoding='utf-8'))['objects']
    for kind in ('table', 'index', 'view', 'trigger'):
        for row in ddl:
            if row['type'] == kind and row.get('sql') and not row['name'].startswith('_cf_'):
                db.execute(row['sql'])
    # Synthetic public catalog parents resolve the two reviewed recurring price
    # FKs. They are excluded from this metadata manifest and are not migrations.
    db.executemany('INSERT INTO plan_catalog(plan_code,rank_order,color_token) VALUES(?,?,?)',
                   [('free', 0, 'neutral'), ('professional', 1, 'blue'), ('dragon', 2, 'red')])
    # Resolve newer prerequisites without changing their existing manifest.
    for name in ('0057-v1.4.0-rebuild-mini-app-storage.sql',
                 '0058-v1.4.0-rebuild-legal-history.sql', '0059-v1.4.0-rebuild-lead-history.sql',
                 '0060-v1.4.0-rebuild-effect-privacy.sql', '0061-v1.4.0-rebuild-release-lease.sql',
                 '0062-v1.4.1-capability-policy.sql', '0063-v1.4.1-grants-overrides.sql',
                 '0064-v1.4.1-audit-rollout.sql', '0065-v1.4.1-privacy-ai-journal.sql'):
        db.executescript((ROOT / 'migrations' / name).read_text(encoding='utf-8'))
    hashes = {}
    stages = {}
    markers = []
    for name, marker in zip(FILES, MARKERS):
        source = (ROOT / 'migrations' / name).read_bytes()
        hashes[name] = hashlib.sha256(source).hexdigest()
        db.executescript(source.decode())
        markers.append(marker)
        tables = TABLES + (ENGINE_TABLES if len(markers) >= 2 else ()) + (PROVIDER_TABLES if len(markers) >= 3 else ()) + (REFUND_TABLES if len(markers) >= 6 else ()) + FINANCIAL
        rows = objects(db, tables)
        stages[marker] = dict(tables=list(tables), objects=rows, markers=list(markers),
            columns={table: [row[1] for row in db.execute('PRAGMA table_info("' + table + '")')]
                     for table in tables}, schemaSha256=hashlib.sha256(compact(rows).encode()).hexdigest())
    if list(db.execute('PRAGMA foreign_key_check')) or db.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
        raise RuntimeError('v143_schema_invalid')
    manifest = dict(version=1, sourceKind='accepted_metadata_fixture_and_reviewed_cumulative_v143_ddl',
                    migrationSha256=hashes, stages=stages, lifecycleTables=list(TABLES + ENGINE_TABLES + PROVIDER_TABLES + REFUND_TABLES))
    source = '// Generated by scripts/v1.4.3-build-lifecycle-schema.py; metadata only.\n' + \
        'const freeze=v=>{if(v&&typeof v==="object"&&!Object.isFrozen(v)){for(const c of Object.values(v))freeze(c);Object.freeze(v);}return v;};\n' + \
        'export const LIFECYCLE_SCHEMA=freeze(' + compact(manifest) + ');\n'
    return source, manifest

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, manifest = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != source:
            raise SystemExit('v143_schema_stale')
    else:
        OUTPUT.write_text(source, encoding='utf-8')
    print(compact(dict(migrationSha256=manifest['migrationSha256'],
                       tables=len(manifest['lifecycleTables']), check=args.check)))

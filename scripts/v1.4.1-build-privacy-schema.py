#!/usr/bin/env python3
"""Compile the separate reviewed P04 schema; never reads live/private data."""
import argparse
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ('0062-v1.4.1-capability-policy.sql', '0063-v1.4.1-grants-overrides.sql',
         '0064-v1.4.1-audit-rollout.sql', '0065-v1.4.1-privacy-ai-journal.sql')
TABLES = ('capability_catalog', 'plan_capabilities', 'entitlement_grants',
          'entitlement_overrides', 'entitlement_decision_audit', 'feature_flags',
          'feature_flag_assignments', 'ai_operation_journal', 'ai_operation_receipts')
OUTPUT = ROOT / 'src/v1.4.1/privacy-schema-manifest.mjs'

def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))

def build():
    db = sqlite3.connect(':memory:')
    db.execute('PRAGMA foreign_keys=ON')
    db.executescript('''
      CREATE TABLE re_schema_migrations(version TEXT PRIMARY KEY);
      CREATE TABLE mini_app_atomic_guards(guard_key TEXT PRIMARY KEY,precondition_ok INTEGER CHECK(precondition_ok=1));
      CREATE TABLE mini_app_privacy_guard(guard_key TEXT PRIMARY KEY,request_id TEXT,subject_id INTEGER,
        reason TEXT,precondition_ok INTEGER,expires_at INTEGER,subject_lead_ids_json TEXT);
      CREATE TABLE privacy_deletion_requests(request_id TEXT PRIMARY KEY,telegram_id INTEGER,status TEXT,expires_at TEXT);
      CREATE TABLE user_roles(telegram_id INTEGER,role TEXT,status TEXT);
      CREATE TABLE partner_profiles(telegram_id INTEGER);
    ''')
    hashes = {}
    for file in FILES:
        source = (ROOT / 'migrations' / file).read_bytes()
        hashes[file] = hashlib.sha256(source).hexdigest()
        db.executescript(source.decode())
    rows = [dict(type=kind, name=name, table_name=table, sql=sql) for kind,name,table,sql in db.execute(
        'SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE tbl_name IN (' +
        ','.join('?' for _ in TABLES) + ') ORDER BY type,name', TABLES)]
    columns = {table: [row[1] for row in db.execute('PRAGMA table_info("'+table+'")')] for table in TABLES}
    if list(db.execute('PRAGMA foreign_key_check')) or db.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
        raise RuntimeError('p04_schema_invalid')
    manifest = dict(version=1,sourceKind='synthetic_reviewed_p04_ddl_only',tables=list(TABLES),
        columns=columns,objects=rows,migrationSha256=hashes,
        schemaSha256=hashlib.sha256(compact(rows).encode()).hexdigest(),
        ledgerVersion='1.4.1-privacy-ai-journal')
    return '// Generated by scripts/v1.4.1-build-privacy-schema.py; no identity or live rows.\n' + \
      'const freeze=v=>{if(v&&typeof v==="object"&&!Object.isFrozen(v)){for(const c of Object.values(v))freeze(c);Object.freeze(v);}return v;};\n' + \
      'export const P04_SCHEMA=freeze('+compact(manifest)+');\n', manifest

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    output,manifest=build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=output: raise SystemExit('p04_schema_stale')
    else: OUTPUT.write_text(output)
    print(compact(dict(tables=len(TABLES),objects=len(manifest['objects']),schemaSha256=manifest['schemaSha256'],check=args.check)))

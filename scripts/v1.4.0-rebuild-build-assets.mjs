import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { transformSync } from "../tests/p11-runtime/node_modules/esbuild/lib/main.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = path.join(root, "src/v1.4.0-rebuild");
const names = ["partner-cabinet.html", "partner-cabinet.css", "partner-cabinet.mjs", "cabinet-theme-bootstrap.js",
  "cabinet-client.mjs", "cabinet-view.mjs", "subscription-view.mjs", "subscription-view.css", "telegram-native.mjs", "telegram-actions-view.mjs", "admin-cabinet.html", "admin-cabinet.css",
  "admin-cabinet.mjs", "admin-client.mjs", "admin-view.mjs"];
const minified = new Set(["cabinet-client.mjs", "cabinet-view.mjs", "subscription-view.mjs"]);
const assets = Object.fromEntries(names.map(name => {
  const source = fs.readFileSync(path.join(directory, "mini-app", name), "utf8");
  const content = minified.has(name)
    ? transformSync(source, { loader: "js", target: "es2022", minify: true, legalComments: "none" }).code : source;
  return [name, { content, sha256: createHash("sha256").update(content).digest("hex"),
    contentType: name.endsWith(".html") ? "text/html; charset=utf-8"
      : name.endsWith(".css") ? "text/css; charset=utf-8" : "text/javascript; charset=utf-8" }];
}));
const bundle = "// Generated by scripts/v1.4.0-rebuild-build-assets.mjs. No offline laboratory.\n" +
  "export const CABINET_ASSETS = Object.freeze(" + JSON.stringify(assets, null, 2) + ");\n";
const stable = fs.readFileSync(path.join(root, "re-program-bot-worker.js"), "utf8");
const start = stable.indexOf("function buildLegacyPlanAuthorityDecision(");
const end = stable.indexOf("\nasync function getServerPlanAuthority(", start);
if (start < 0 || end < start) throw new Error("accepted plan fallback is missing");
const policy = "// Generated unchanged pure fallback from accepted v1.3.9. No reconciliation or writes.\nexport " +
  stable.slice(start, end).trimEnd() + "\n";
for (const [name, content] of [["cabinet-assets.mjs", bundle], ["existing-plan-policy.mjs", policy]]) {
  const target = path.join(directory, name);
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== content) throw new Error(name + " is stale");
  } else fs.writeFileSync(target, content);
}
console.log(process.argv.includes("--check") ? "P09 assets and accepted plan policy: current" : "P09 assets and accepted plan policy: generated");
